/*
    CREATE TABLES
*/

-- ORDER ITEMS
CREATE TABLE TBL_ORDER_ITEMS(
    ORDER_ITEM_ID INT PK,
    ORDER_ID INT,
    MENU_ITEM_ID INT,
    QUANTITY INT,
    UNIT_PRICE DECIMAL(10,2),
    NOTES VARCHAR(100),
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- MENU ITEMS
CREATE TABLE TBL_MENU_ITEMS(
    MENU_ITEM_ID INT PK,
    CATEGORY_ID INT,
    ITEM_NAME VARCHAR(30),
    ITEM_DESCRIPTION VARCHAR(80),
    PRICE DECIMAL(10,2),
    ISACTIVE BOOLEAN,
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- MENU ITEM MODIFIERS
CREATE TABLE TBL_MENU_ITEMS_MODIFIERS(
    MENU_ITEM_ID INT,
    MODIFIER_ID INT,
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- MENU ITEM MODIFIERS
CREATE TABLE TBL_MODIFIERS(
    MODIFIER_ID INT PK,
    MOD_NAME VARCHAR(40),
    EXTRA_PRICE DECIMAL(10,2),
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- MENU CATEGORIES
CREATE TABLE TBL_MENU_CATEGORIES(
    CATEGORY_ID INT PK,
    MENU_CATEGORY_NAME VARCHAR(20) UNIQUE,
    MENU_CATEGORY_DESCRIPTION VARCHAR(80) UNIQUE,
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- WAITLIST ENTRIES
CREATE TABLE TBL_WAITLIST_ENTRIES(
    WAITLIST_ID INT PK,
    USER_ID INT,
    PARTY_SIZE INT,
    JOINED_AT DATETIME,
    WAIT_STATUS VARCHAR(15),
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- TABLES
CREATE TABLE TBL_TABLES(
    TABLE_ID INT PK,
    TABLE_NUMBER INT,
    CAPACITY INT,
    TABLE_LOCATION VARCHAR(50),
    TABLE_STATUS VARCHAR(20),
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- ORDERS
CREATE TABLE TBL_ORDERS(
    ORDER_ID INT PK,
    USER_ID INT,
    TABLE_ID INT,
    RESERVATION_ID INT,
    SUBTOTAL DECIMAL(10,2),
    TAX DECIMAL(10,2),
    TOTAL DECIMAL(10,2),
    ORDER_TYPE VARCHAR(30),
    ORDER_STATUS VARCHAR(20),
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- ROLES
CREATE TABLE TBL_ROLES(
    ROLE_ID INT PK,
    ROLE_NAME VARCHAR(30),
    ROLE_DESCRIPTION VARCHAR(80),
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- USERS
CREATE TABLE TBL_USERS(
    USER_ID INT PK,
    ROLE_ID INT,
    USERNAME VARCHAR(30),
    EMAIL VARCHAR(80),
    PHONE VARCHAR(15),
    PASSWORD_HASH VARCHAR(20),
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- RESERVATIONS
CREATE TABLE TBL_RESERVATIONS(
    RESERVATION_ID INT PK,
    USER_ID INT,
    TABLE_ID INT,
    SCHEDULE_DATE DATETIME,
    PARTY_SIZE INT,
    RESERVATION_STATUS VARCHAR(10),
    CREATE_DATE DATE,
    MOD_DATE DATE
);

-- EMPLOYEES
CREATE TABLE TBL_EMPLOYEES(
    EMPLOYEE_ID INT PK,
    USER_ID INT,
    FIRST_NAME VARCHAR(30),
    LAST_NAME VARCHAR(30),
