package Models;

public class SupplierOrder {

    private int idSupplierOrder, idSupplier;
    private String supplier, orderDate, status, createDate, modDate;

    public int getIdSupplierOrder() {
        return idSupplierOrder;
    }

    public void setIdSupplierOrder(int idSupplierOrder) {
        this.idSupplierOrder = idSupplierOrder;
    }

    public int getIdSupplier() {
        return idSupplier;
    }

    public void setIdSupplier(int idSupplier) {
        this.idSupplier = idSupplier;
    }

    public String getSupplier() {
        return supplier;
    }

    public void setSupplier(String supplier) {
        this.supplier = supplier;
    }

    public String getOrderDate() {
        return orderDate;
    }

    public void setOrderDate(String orderDate) {
        this.orderDate = orderDate;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getCreateDate() {
        return createDate;
    }

    public void setCreateDate(String createDate) {
        this.createDate = createDate;
    }

    public String getModDate() {
        return modDate;
    }

    public void setModDate(String modDate) {
        this.modDate = modDate;
    }


    
}
